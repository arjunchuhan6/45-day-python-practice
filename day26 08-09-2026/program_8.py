# Python Program 8: Deactivate a virtual environment

# Run this command while the virtual environment is active:
# deactivate

# Explanation:
# deactivate exits the current virtual environment.
# The (.venv) label disappears from the PowerShell prompt.
# Python and pip then return to the system or previously active environment.

# Deactivation does not delete the .venv folder or its installed packages.
# You can activate the same environment again whenever you need it.

print("Program 8: Deactivate the environment with 'deactivate'")
