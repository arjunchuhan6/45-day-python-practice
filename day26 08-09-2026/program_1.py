# Python Program 1: Create a virtual environment

# Run this command in PowerShell from your project folder:
# python -m venv .venv

# Explanation:
# python       starts the Python interpreter.
# -m           runs a Python module as a program.
# venv         is Python's built-in virtual environment module.
# .venv        is the folder name for the new environment.

# The command creates an isolated Python environment inside the .venv folder.
# It also creates a separate Python interpreter and pip for this project.
# Packages installed in this environment do not affect other projects.

print("Program 1: Create a virtual environment with 'python -m venv .venv'")