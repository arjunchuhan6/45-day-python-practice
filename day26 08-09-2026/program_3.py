# Python Program 3: Install a package

# Activate the virtual environment before running this command:
# .\.venv\Scripts\Activate.ps1

# Install the requests package with pip:
# python -m pip install requests

# Explanation:
# python -m pip makes sure pip belongs to the active Python interpreter.
# install tells pip to download and install a package.
# requests is the package that will be installed.

# You can replace requests with another package name, for example:
# python -m pip install colorama

print("Program 3: Install a package with 'python -m pip install requests'")
